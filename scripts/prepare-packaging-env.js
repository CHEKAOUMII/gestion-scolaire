'use strict';

/**
 * Generates the filtered .env that ships inside the installer (resources/.env).
 *
 * The developer .env contains build-time credentials (GH_TOKEN) and provisioning
 * secrets (GESTION_BOOTSTRAP_SECRET, OWNER_SYNC_*) that must never be distributed
 * to installed devices. Only the runtime Firebase web-client config — public
 * identifiers that main/firebase/config.js can equally read from sync_config —
 * plus the functions URL belong in the package.
 *
 * Usage:
 *   node scripts/prepare-packaging-env.js                       (default allowlist)
 *   node scripts/prepare-packaging-env.js --with-bootstrap-secret
 *                               (opt-in: ship GESTION_BOOTSTRAP_SECRET so
 *                                institution bootstrap/link stays enabled)
 *
 * Exits non-zero only on filesystem errors — a missing key is a loud warning so
 * a release never silently ships an empty config when the operator forgot to
 * provision it.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE_ENV = path.join(ROOT, '.env');
const OUTPUT_DIR = path.join(ROOT, 'packaging', 'generated');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'app.env');

// Runtime-safe keys: Firebase web client identifiers (public by design) + URL.
const ALLOWED_KEYS = [
    'FIREBASE_FUNCTIONS_URL',
    'FIREBASE_API_KEY',
    'FIREBASE_AUTH_DOMAIN',
    'FIREBASE_PROJECT_ID',
    'FIREBASE_STORAGE_BUCKET',
    'FIREBASE_MESSAGING_SENDER_ID',
    'FIREBASE_APP_ID'
];

const OPT_IN_FLAGS = {
    '--with-bootstrap-secret': 'GESTION_BOOTSTRAP_SECRET'
};

// Credentials that must never ship. Listed explicitly so a new secret added to
// .env fails loudly here instead of silently riding into the installer.
const FORBIDDEN_KEYS = ['GH_TOKEN', 'PENCIL_DEV_PASSWORD_HASH'];

function main() {
    const optIn = process.argv.slice(2).filter((arg) => OPT_IN_FLAGS[arg]);
    const allowed = new Set(ALLOWED_KEYS);
    for (const flag of optIn) allowed.add(OPT_IN_FLAGS[flag]);

    let source = {};
    if (fs.existsSync(SOURCE_ENV)) {
        source = require('dotenv').parse(fs.readFileSync(SOURCE_ENV));
    } else {
        console.warn('[prepare-packaging-env] no local .env found — generating an empty template.');
    }

    const lines = [
        '# AUTO-GENERATED by scripts/prepare-packaging-env.js — do not edit by hand.',
        '# Filtered from the build machine .env; secrets (GH_TOKEN, OWNER_SYNC_*, ...)',
        '# are intentionally excluded from the distribution.',
        ''
    ];
    const shipped = [];
    for (const key of allowed) {
        if (source[key] !== undefined) {
            lines.push(`${key}=${source[key]}`);
            shipped.push(key);
        }
    }

    const skipped = Object.keys(source).filter((key) => !allowed.has(key));
    for (const key of skipped) {
        const reason = FORBIDDEN_KEYS.includes(key) ? 'FORBIDDEN (credential)' : 'not in allowlist';
        console.warn(`[prepare-packaging-env] excluding ${key}: ${reason}`);
    }
    if (!shipped.includes('FIREBASE_PROJECT_ID')) {
        console.warn(
            '[prepare-packaging-env] FIREBASE_PROJECT_ID missing — packaged app will rely on the sync_config DB fallback.'
        );
    }

    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
    console.log(`[prepare-packaging-env] wrote ${path.relative(ROOT, OUTPUT_FILE)} (${shipped.length} keys: ${shipped.join(', ') || 'none'})`);
}

try {
    main();
} catch (err) {
    console.error('[prepare-packaging-env] failed:', err?.message || err);
    process.exit(1);
}
